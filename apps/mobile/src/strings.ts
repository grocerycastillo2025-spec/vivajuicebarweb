/** Cambia, sección por sección, los textos del objeto vivo. */
export function replaceStrings(source: Strings): void {
  for (const key of Object.keys(source) as (keyof Strings)[]) {
    (strings as Record<keyof Strings, unknown>)[key] = source[key];
  }
}
